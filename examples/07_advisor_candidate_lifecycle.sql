-- Example 7: advisor is not magic.  The advisor proposes hypotheses (local,
-- single-query index candidates); pathprobe measures what happened to each
-- of them in planner competition.
--   psql -X -f examples/07_advisor_candidate_lifecycle.sql
-- See docs/examples/07-advisor-candidate-lifecycle.md.

\ir _common.sql

DROP TABLE IF EXISTS ex7_orders;
CREATE TABLE ex7_orders (id int PRIMARY KEY, customer_id int, status int,
                         created date, note text);
INSERT INTO ex7_orders
SELECT g, g % 2000, g % 5, date '2026-01-01' + (g % 365), repeat('n', 30)
FROM generate_series(1, 30000) g;
ANALYZE ex7_orders;

\set q 'SELECT * FROM ex7_orders WHERE customer_id = 42 AND status = 3 ORDER BY created'

-- What EXPLAIN shows: no index on customer_id or status exists.
EXPLAIN (COSTS OFF) :q;

-- One lifecycle row per advisor candidate.  The chain, left to right:
-- generated by the advisor (ddl) -> injected -> IndexPath generated? ->
-- add_path() outcome (counts, fate) -> used by the final plan?
CREATE FUNCTION pg_temp.ex7_lifecycle(q text, spec text)
RETURNS TABLE (hypo text, ddl text, injected bool, paths_built int,
               acc int, rej int, disp int, surv int, fate text, in_plan bool)
LANGUAGE sql AS $$
  SELECT h->>'name', h->>'ddl', (h->>'injected')::bool,
         (h->'index_build'->>'generated')::int,
         (h->>'accepted')::int, (h->>'rejected')::int,
         (h->>'displaced')::int, (h->>'survived')::int,
         h->>'fate' || coalesce('(' || (h->>'fate_reason') || ')', ''),
         (h->>'in_plan')::bool
  FROM jsonb_array_elements(pathprobe_propose_json(q, spec)::jsonb->'hypo_indexes') h
$$;

SELECT * FROM pg_temp.ex7_lifecycle(:'q', '{"advise": true}');

-- The advisor block and the coverage of this run.
SELECT j->'advisor' AS advisor,
       j->'coverage' AS coverage
FROM (SELECT pathprobe_propose_json(:'q', '{"advise": true}')::jsonb AS j) s;

-- The events behind "displaced": every path of one candidate is pushed out
-- by a path of a later one.  The displacer is the ACCEPTED event right
-- before each DISPLACED one (same gap_cost).
SELECT (e->>'seq')::int AS seq, e->>'pathtype' AS path, e->>'kind' AS event,
       e->>'label' AS label, e->>'gap_cost' AS gap_cost
FROM jsonb_array_elements(pathprobe_propose_json(:'q', '{"advise": true}')::jsonb->'events') e
WHERE e->>'rel' = '{1}' AND e->>'kind' IN ('accepted', 'displaced')
ORDER BY 1;

-- Structural checks; no cost values are asserted.
WITH j AS (SELECT pathprobe_propose_json(:'q', '{"advise": true}')::jsonb AS j),
     h AS (SELECT x FROM j, jsonb_array_elements(j->'hypo_indexes') x)
SELECT pg_temp.ex_check(label, ok) AS "check"
FROM (VALUES
  ('the advisor ran and generated several candidates',
   (SELECT (j->'advisor'->>'enabled')::bool FROM j)
   AND (SELECT count(*) FROM h) >= 3),
  ('index build decisions and add_path() outcomes are covered',
   (SELECT (j->'coverage'->>'index_build')::bool
           AND (j->'coverage'->>'add_path_accepted')::bool
           AND (j->'coverage'->>'add_path_displaced')::bool FROM j)),
  ('every candidate was injected and built index paths',
   (SELECT bool_and((x->>'injected')::bool
                    AND (x->'index_build'->>'generated')::int > 0) FROM h)),
  ('exactly one candidate is in the final plan, and it survived',
   (SELECT count(*) = 1 AND bool_and(x->>'fate' = 'survived')
    FROM h WHERE (x->>'in_plan')::bool)),
  ('the (customer_id, status) candidate is the one in the plan',
   (SELECT bool_or(x->>'ddl' LIKE '%(customer_id, status)') FROM h
    WHERE (x->>'in_plan')::bool)),
  ('some candidate was accepted and then displaced',
   (SELECT bool_or(x->>'fate' = 'displaced' AND (x->>'accepted')::int > 0) FROM h)),
  ('some candidate was rejected outright',
   (SELECT bool_or(x->>'fate' = 'rejected' AND (x->>'accepted')::int = 0) FROM h)),
  ('a candidate can survive at its relation and still not be in the plan',
   (SELECT bool_or(x->>'fate' = 'survived' AND NOT (x->>'in_plan')::bool) FROM h)),
  ('the query-level benefit is baseline_cost - plan_cost',
   (SELECT abs((j->'advisor'->>'baseline_cost')::numeric
               - (j->'advisor'->>'plan_cost')::numeric
               - (j->'advisor'->>'query_level_benefit')::numeric) < 0.011 FROM j))) v(label, ok);

DROP TABLE ex7_orders;
